"""
EXP-013 hyper-parameter search for the raw model (reference + tampered input).

Step by step: each step tries a few values of ONE setting, keeps the best by
validation AUC, and carries it into the next step. Test numbers are logged but
never used to choose anything.

Fixed (as in every earlier run): siamese_diff depth 1, ImageNet start,
AdamW lr 3e-4, cosine schedule, 15 epochs, batch 32, BCE + 0.3 x "which tamper?",
best epoch by validation AUC. Data: data/synth_v2, NORVIA + multi-font, raw crops.

Steps (agreed: ~8 runs):
  A  baseline                         weight decay 1e-4, no dropout, BCE, no augmentation
  B  weight decay 1e-3, 1e-2          the main overfitting control
  C  dropout 0.3                      the other usual remedy
  D  augmentation                     photometric + small camera move of the tampered crop
  E  loss: label smoothing 0.1, focal BCE is the natural choice for balanced yes/no data;
                                      smoothing fights over-confidence, focal tests hard examples
  F  best setting again with seed 1   how much is run-to-run noise
A change is kept only if it beats the current best by more than NOISE (EXP-007
measured ~0.006 spread between identical runs), otherwise the simpler setting stays.

Every run logs to TensorBoard (outputs/tensorboard/<run>) and saves best.pt,
metrics.json, predictions.csv in outputs/exp007/<run>, plus a training log.
The tuning log with reasons is rewritten after every run:
experiments/EXP-013_tuning_log.md

Run: python src/exp013_sweep.py
"""
import json
import subprocess
import sys

from common import OUTPUTS, ROOT

BASE = ["--arch", "siamese_diff", "--data", "data/synth_v2", "--sets", "D1,D2", "--raw-crops",
        "--depth", "1", "--batch", "32", "--input-w", "448", "--input-h", "192"]
NOISE = 0.01
LOG = ROOT / "experiments" / "EXP-013_tuning_log.md"
done = []      # (step, run, change, why, settings, metrics, decision)


def run(name, settings):
    out = OUTPUTS / "exp007" / name
    if not (out / "metrics.json").exists():
        args = ["--weight-decay", str(settings["wd"]), "--dropout", str(settings["dropout"]),
                "--loss", settings["loss"], "--label-smoothing", str(settings["smoothing"]),
                "--seed", str(settings["seed"])]
        if settings["augment"]:
            args += ["--augment", "--geo-augment"]
        log = OUTPUTS / "exp007" / "logs" / f"{name}.log"
        print(f"start {name}: {' '.join(args)}", flush=True)
        with open(log, "w") as f:
            subprocess.run([sys.executable, str(ROOT / "src" / "train_pairs.py"), *BASE, "--run", name, *args],
                           stdout=f, stderr=subprocess.STDOUT, check=True)
    m = json.loads((out / "metrics.json").read_text())
    best = next(h for h in m["history"] if h["epoch"] == m["best_epoch"])
    train_auc = next(v for k, v in best.items() if k.startswith("train_") and k.endswith("/auc"))
    res = m["results"]
    return {"val": m["best_val_auc"], "train_at_best": train_auc, "gap": train_auc - m["best_val_auc"],
            "best_epoch": m["best_epoch"],
            "test_D2": res.get("test_D2", {}).get("auc"), "test_D1": res.get("test_D1", {}).get("auc"),
            "unseen": res.get("test_unseen_font_D1", {}).get("auc")}


def write_log():
    f = lambda v: "" if v is None else f"{v:.3f}"
    lines = ["# EXP-013 tuning log (generated by `src/exp013_sweep.py`)", "",
             "Raw model (reference + tampered input, both cropped with background), siamese_diff depth 1, "
             "data/synth_v2. Chosen by **validation AUC only**; a change is kept only if it beats the current "
             f"best by more than {NOISE}. 'gap' = training AUC minus validation AUC at the best epoch "
             "(large gap = overfitting). Test columns are for the record, not for choosing.", "",
             "| step | run | change | why | val AUC | train AUC | gap | best epoch | test NORVIA | test multi-font | unseen font | decision |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for step, name, change, why, _, m, decision in done:
        lines.append(f"| {step} | {name} | {change} | {why} | {f(m['val'])} | {f(m['train_at_best'])} | {f(m['gap'])} | "
                     f"{m['best_epoch']} | {f(m['test_D2'])} | {f(m['test_D1'])} | {f(m['unseen'])} | {decision} |")
    LOG.write_text("\n".join(lines) + "\n")


def step(label, current, current_m, current_name, trials):
    """
    Try each (name, change, why, settings). The best trial is kept only if it
    beats the current setting by more than NOISE; otherwise the current stays.
    Returns the (settings, metrics, run name) to carry forward.
    """
    results = []
    for name, change, why, settings in trials:
        results.append((name, change, why, settings, run(name, settings)))
    winner = max(results, key=lambda r: r[4]["val"])
    keep = winner[4]["val"] > current_m["val"] + NOISE
    for name, change, why, settings, m in results:
        if keep and name == winner[0]:
            decision = f"**kept** (val {m['val'] - current_m['val']:+.3f})"
        else:
            decision = f"not kept (val {m['val'] - current_m['val']:+.3f} vs {current_name})"
        done.append((label, name, change, why, settings, m, decision))
    write_log()
    return (winner[3], winner[4], winner[0]) if keep else (current, current_m, current_name)


def main():
    base = {"wd": 1e-4, "dropout": 0.0, "loss": "bce", "smoothing": 0.0, "augment": False, "seed": 0}
    cur, cur_m, cur_name = base, run("e13_base", base), "e13_base"
    done.append(("A", "e13_base", "baseline", "same settings as earlier runs, new 10K data", base, cur_m, "starting point"))
    write_log()

    cur, cur_m, cur_name = step("B", cur, cur_m, cur_name, [
        ("e13_wd1e-3", "weight decay 1e-3", "stronger pull of the weights towards zero = less memorising", {**cur, "wd": 1e-3}),
        ("e13_wd1e-2", "weight decay 1e-2", "much stronger; checks whether more is better", {**cur, "wd": 1e-2})])
    cur, cur_m, cur_name = step("C", cur, cur_m, cur_name, [
        ("e13_drop", "dropout 0.3", "randomly drops features before the heads, so no single feature can be memorised",
         {**cur, "dropout": 0.3})])
    cur, cur_m, cur_name = step("D", cur, cur_m, cur_name, [
        ("e13_aug", "augmentation on", "photometric noise + a small camera move of the tampered crop = more variety from the same data",
         {**cur, "augment": True})])
    cur, cur_m, cur_name = step("E", cur, cur_m, cur_name, [
        ("e13_ls", "label smoothing 0.1", "stops the model pushing towards 100 % certainty on training pairs", {**cur, "smoothing": 0.1}),
        ("e13_focal", "focal loss (gamma 2)", "puts more weight on the hard examples (subtle tampers)", {**cur, "loss": "focal"})])

    m = run("e13_best_s1", {**cur, "seed": 1})
    done.append(("F", "e13_best_s1", f"setting of {cur_name}, seed 1", "how much of the result is run-to-run noise",
                 {**cur, "seed": 1}, m, f"seed difference {m['val'] - cur_m['val']:+.3f}"))
    write_log()
    (OUTPUTS / "exp013").mkdir(parents=True, exist_ok=True)
    (OUTPUTS / "exp013" / "best_setting.json").write_text(
        json.dumps({"best_run": cur_name, "settings": cur, "val_auc": cur_m["val"], "seed1_run": "e13_best_s1"}, indent=1))
    print("best:", cur_name, cur, "val", round(cur_m["val"], 4))


if __name__ == "__main__":
    main()
