"""
Dataset statistics for the synthetic data (EXP-003), written as markdown.

Counts per dataset folder, set (D1 = multi-font words, D2 = NORVIA), split,
class (genuine / tampered) and tamper type, plus how many NORVIA samples have a
registration-made crop (F12; only those are used for training/evaluation).

Run: python src/dataset_stats.py      -> experiments/EXP-003_dataset_stats.md
"""
import csv
from collections import Counter

from common import ROOT

FOLDERS = ["data/synth", "data/synth_more"]
TAMPERS = ["none", "stretch", "recolour", "respace", "glyph_swap", "font_swap", "overlap", "cut"]


def registered(folder):
    f = ROOT / folder / "registration_D2.csv"
    return {r["id"] for r in csv.DictReader(open(f)) if r["registered"] == "True"} if f.exists() else set()


def main():
    lines = ["# EXP-003 dataset statistics (generated by `src/dataset_stats.py`)", "",
             "D1 = made-up words in 9 fonts (multi-font set); D2 = the real NORVIA artwork. "
             "Class 0 = genuine (camera effects only), class 1 = tampered. "
             "\"usable\" = D2 samples whose synthetic photo was registered by the EXP-001 code (F12 crops); "
             "unregistered D2 samples are skipped by training and evaluation. D1 samples are all usable.", ""]
    grand = Counter()
    for folder in FOLDERS:
        rows = list(csv.DictReader(open(ROOT / folder / "labels.csv")))
        reg = registered(folder)
        lines += [f"## `{folder}` ({len(rows)} samples)", "",
                  "| set | split | genuine (0) | tampered (1) | total | usable (after registration) |",
                  "|---|---|---|---|---|---|"]
        for s in ("D2", "D1"):
            for split in ("train", "val", "test", "test_unseen_font", "skip_unseen_font"):
                sel = [r for r in rows if r["set"] == s and r["split"] == split]
                if not sel:
                    continue
                g = sum(r["label"] == "0" for r in sel)
                t = len(sel) - g
                usable = sum(r["id"] in reg for r in sel) if s == "D2" else len(sel)
                lines.append(f"| {s} | {split} | {g} | {t} | {len(sel)} | {usable} |")
                grand[(folder, s, split, "usable")] += usable
        lines += ["", "Samples per tamper type (all splits):", "",
                  "| set | " + " | ".join(TAMPERS) + " |", "|---|" + "---|" * len(TAMPERS)]
        for s in ("D2", "D1"):
            c = Counter(r["tamper"] for r in rows if r["set"] == s)
            lines.append(f"| {s} | " + " | ".join(str(c.get(t, 0)) for t in TAMPERS) + " |")
        fonts = Counter(r["font"] for r in rows if r["set"] == "D1")
        lines += ["", "D1 samples per font: " + ", ".join(f"{k} {v}" for k, v in sorted(fonts.items(), key=lambda x: -x[1])), ""]

    def n(folder, s, split):
        return grand[(folder, s, split, "usable")]

    base_train = n("data/synth", "D2", "train") + n("data/synth", "D1", "train")
    more_train = n("data/synth_more", "D2", "train") + n("data/synth_more", "D1", "train")
    lines += ["## Training pairs actually used per model configuration", "",
              "| configuration | example runs | training pairs | validation | test sets |",
              "|---|---|---|---|---|",
              f"| D1+D2, original data | sd_base, sd_depth1, ef_base, dino_base, … | {base_train} "
              f"(D2 {n('data/synth', 'D2', 'train')} + D1 {n('data/synth', 'D1', 'train')}) | "
              f"{n('data/synth', 'D2', 'val') + n('data/synth', 'D1', 'val')} mixed | "
              f"NORVIA {n('data/synth', 'D2', 'test')}, multi-font {n('data/synth', 'D1', 'test')}, unseen font {n('data/synth', 'D1', 'test_unseen_font')} |",
              f"| D1+D2 + extra data | sd_more, sd_depth1_more | {base_train + more_train} "
              f"(+ D2 {n('data/synth_more', 'D2', 'train')} + D1 {n('data/synth_more', 'D1', 'train')}) | same | same |",
              f"| NORVIA only + extra data | norvia_448, norvia_896 | "
              f"{n('data/synth', 'D2', 'train') + n('data/synth_more', 'D2', 'train')} | "
              f"{n('data/synth', 'D2', 'val')} NORVIA | NORVIA {n('data/synth', 'D2', 'test')} |",
              "", "Validation and test sets are always taken from `data/synth` only (the extra data is training-only), "
              "so all runs are evaluated on the same samples. Per-tamper test numbers rest on ~13-15 samples each."]
    # Class balance of the final model's training set (sd_depth1_more / sd_more).
    final = []
    for folder in FOLDERS:
        reg = registered(folder)
        final += [r for r in csv.DictReader(open(ROOT / folder / "labels.csv"))
                  if r["split"] == "train" and (r["set"] == "D1" or r["id"] in reg)]
    c = Counter((r["set"], r["tamper"]) for r in final)
    lab = Counter((r["set"], r["label"]) for r in final)
    lines += ["", "## Final training set of the recommended model (`sd_depth1_more`, also `sd_more`)", "",
              "| set | genuine (0) | tampered (1) | " + " | ".join(TAMPERS[1:]) + " | total |",
              "|---|---|---|" + "---|" * 7 + "---|"]
    for s_ in ("D2", "D1"):
        lines.append(f"| {s_} | {lab[(s_, '0')]} | {lab[(s_, '1')]} | " + " | ".join(str(c[(s_, t)]) for t in TAMPERS[1:])
                     + f" | {lab[(s_, '0')] + lab[(s_, '1')]} |")
    g = lab[("D2", "0")] + lab[("D1", "0")]
    t_ = lab[("D2", "1")] + lab[("D1", "1")]
    lines.append(f"| **all** | **{g}** | **{t_}** | " + " | ".join(str(c[("D2", x)] + c[("D1", x)]) for x in TAMPERS[1:])
                 + f" | **{g + t_}** |")
    lines += ["", "Balanced by design: half of all samples genuine; the 7 tamper types in equal turns. "
              "Small deviations come from samples skipped because their synthetic photo could not be registered."]

    out = ROOT / "experiments" / "EXP-003_dataset_stats.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
