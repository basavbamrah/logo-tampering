"""
Final per-photo results for the 50 real photos, in one table and one folder.

Collects what the end-to-end run (run_final.sh) produced and puts it side by side:
  alignment (EXP-001)      registered?, inliers, ECC score
  cut-off (EXP-010)        % of the reference ink outside the photo
  shape (EXP-010, 008)     worst part difference %, largest letter shift
  colour (EXP-005)         hue flag and hue difference per part
  model (e14_consistent)   p(tampered) mean of the 3 references, decision, tamper type

It does not invent a new combined verdict. It lists which methods flag each
photo ("evidence"); the model's decision stays the model's decision.

Output: outputs/final/final_results.csv, outputs/final/README.md
Run: python src/final_report.py [--model e14_consistent]
"""
import argparse
import csv
import shutil

from common import OUTPUTS

OUT = OUTPUTS / "final"
FLOW_THRESHOLD = 0.17     # EXP-008: 95th percentile of genuine synthetic max_dev (half-size px)
SHAPE_THRESHOLD = 1.0     # EXP-010: worst part difference above this % counts as a shape difference
CUT_THRESHOLD = 1.0       # EXP-010: % of reference ink outside the photo


def read(path, key="image"):
    return {r[key]: r for r in csv.DictReader(open(path))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="e14_consistent")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    reg = read(OUTPUTS / "exp001" / "registration.csv")
    diff = read(OUTPUTS / "exp010" / "diff_scores.csv")
    flow = read(OUTPUTS / "exp008" / "real_letter_shifts.csv")
    hue = read(OUTPUTS / "exp005" / "real_colour.csv")
    model = read(OUTPUTS / "exp007" / args.model / "real_predictions.csv")

    rows = []
    for image in sorted(reg):
        r, d, f, h, m = reg[image], diff.get(image, {}), flow.get(image, {}), hue.get(image, {}), model.get(image, {})
        evidence = []
        if r["registered"] != "True":
            evidence.append("can't register")
        cut = float(d.get("cut_pct") or 0)
        if cut > CUT_THRESHOLD:
            evidence.append("cut-off")
        shape_pct = float(d.get("worst_part_pct") or 0)
        max_dev = float(f.get("max_dev_px") or 0) if f.get("max_dev_px") not in ("", "nan", None) else 0.0
        if shape_pct > SHAPE_THRESHOLD:
            evidence.append("difference map")
        if max_dev > FLOW_THRESHOLD:
            evidence.append("letter shift")
        if h.get("flag_hue") == "True":
            evidence.append("colour")
        if m.get("decision", "").startswith("tampered"):
            evidence.append("model")
        rows.append({
            "image": image, "registered": r["registered"], "inliers": r["inliers"], "ecc": r["ecc_corr"],
            "cut_pct": d.get("cut_pct", ""), "shape_worst_part_pct": d.get("worst_part_pct", ""),
            "flow_max_dev_halfpx": f.get("max_dev_px", ""), "hue_flag": h.get("flag_hue", ""),
            "hue_icon": h.get("hue_icon", ""), "hue_word": h.get("hue_word", ""), "hue_tagline": h.get("hue_tagline", ""),
            "model_p": m.get("p_mean", ""), "model_decision": m.get("decision", ""), "model_kind": m.get("kind", ""),
            "evidence": "; ".join(evidence) or "none", "n_methods_flagging": sum(e not in ("can't register",) for e in evidence),
        })

    with open(OUT / "final_results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=rows[0].keys())
        w.writeheader()
        w.writerows(rows)

    sheet = OUTPUTS / "exp007" / args.model / "real_heatmaps_sheet.jpg"
    if sheet.exists():
        shutil.copy(sheet, OUT / "model_heatmaps_sheet.jpg")

    groups = {}
    for row in rows:
        groups.setdefault(row["evidence"], []).append(row["image"])
    lines = ["# Final results on the 50 real photos (generated by `src/final_report.py`)", "",
             f"Model: `{args.model}`. No ground truth exists for these photos: this lists evidence, not verified answers.",
             "Thresholds: cut-off > 1 % of the ink outside the photo; difference map > 1 %; letter shift > 0.17 half-size px "
             "(95th percentile of genuine synthetic); colour = EXP-005 hue flag; model = its own validation thresholds.", "",
             "| evidence | photos |", "|---|---|"]
    for ev, imgs in sorted(groups.items(), key=lambda kv: (-len(kv[0].split("; ")) if kv[0] != "none" else 99, kv[0])):
        lines.append(f"| {ev} | {' '.join(imgs)} |")
    dec = [row["model_decision"].split(" +")[0] for row in rows]
    lines += ["", "Model decisions: " + ", ".join(f"{b} {dec.count(b)}" for b in ("tampered", "don't know", "genuine", "flagged: can't register")),
              "", "Files: `final_results.csv` (one row per photo, all numbers), `model_heatmaps_sheet.jpg`; "
              "per-method details in `outputs/exp001`, `exp005`, `exp008`, `exp010`, `exp007/<model>/`."]
    (OUT / "README.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
