"""
Model registry: which run name means which configuration.

Reads outputs/exp007/<run>/config.json (exactly what was passed to
train_pairs.py) and metrics.json (results) for every finished run and writes
experiments/EXP-007_model_registry.md. Options that did not exist yet when an
early run was trained are shown with the value the code used then (its default).

Run: python src/model_registry.py
"""
import json

from common import OUTPUTS, ROOT

# Defaults of train_pairs.py (used for runs trained before an option existed).
DEFAULTS = {"depth": 2, "dropout": 0.0, "kind_weight": 0.3, "loss": "bce", "lr": 3e-4, "weight_decay": 1e-4,
            "batch": 32, "epochs": 15, "input_w": 448, "input_h": 128, "sets": "D1,D2", "extra_data": "",
            "augment": False, "freeze_stem": False, "full_res": False, "raw_crops": False, "seed": 0}

# Things the config file cannot show.
RUN_NOTES = {
    "sd_base": "first run; original DataLoader code",
    "sd_base_cache": "same settings as sd_base; in-memory image-cache code (refactor check)",
    "dino_base": "model resizes input to 448x126 (multiple of 14)",
    "norvia_896": "eval batch 16, image caches in CPU memory (memory settings only)",
    "exp012_raw": "EXP-012: candidate = un-straightened loose crop (control: norvia_448)",
    "e14_consistent": "EXP-014 FINAL MODEL: data/synth_v2, every crop registered (NORVIA and multi-font)",
}

ENCODER = {
    "siamese_diff": "ResNet-18 (ImageNet), first {depth} stage(s), shared by both inputs",
    "early_fusion": "full ResNet-18 (ImageNet), first conv widened to 6 channels",
    "dino_frozen": "DINOv2 ViT-S/14, frozen",
}


def main():
    rows = []
    for metrics_file in sorted((OUTPUTS / "exp007").glob("*/metrics.json")):
        folder = metrics_file.parent
        m = json.loads(metrics_file.read_text())
        cfg = {**DEFAULTS, **json.loads((folder / "config.json").read_text())}
        arch = cfg["arch"]
        res = m["results"]
        data = "NORVIA only (D2)" if cfg["sets"] == "D2" else "NORVIA + multi-font (D1+D2)"
        if cfg["extra_data"]:
            data += " + extra (synth_more)"
        notes = [RUN_NOTES[m["run"]]] if m["run"] in RUN_NOTES else []
        if cfg["augment"]:
            notes.append("augment")
        if cfg["freeze_stem"]:
            notes.append("frozen stem+layer1")
        if cfg["dropout"]:
            notes.append(f"dropout {cfg['dropout']}")
        if cfg["full_res"]:
            notes.append("full-res crops")
        if cfg["raw_crops"]:
            notes.append("raw (un-straightened) crops")
        rows.append({
            "run": m["run"], "arch": arch,
            "encoder": ENCODER[arch].format(depth=cfg["depth"]),
            "depth": cfg["depth"] if arch == "siamese_diff" else "-",
            "input": f"{cfg['input_w']}x{cfg['input_h']}", "data": data,
            "loss": f"{cfg['loss']}" + (f" (gamma {cfg.get('gamma', 2.0)})" if cfg["loss"] == "focal" else "")
                    + f" + {cfg['kind_weight']} x CE(8)",
            "opt": f"AdamW lr {cfg['lr']:g}, wd {cfg['weight_decay']:g}",
            "batch": cfg["batch"], "seed": cfg["seed"], "other": ", ".join(n for n in notes if n) or "-",
            "best_epoch": m["best_epoch"], "val": round(m["best_val_auc"], 3),
            "val_set": "NORVIA" if cfg["sets"] == "D2" else "mixed",
            "test_d2": round(res["test_D2"]["auc"], 3),
            "unseen": round(res["test_unseen_font_D1"]["auc"], 3) if "test_unseen_font_D1" in res else "n/a",
        })

    rows.sort(key=lambda r: (r["val_set"] != "mixed", -r["test_d2"]))
    lines = [
        "# EXP-007 model registry (generated by `src/model_registry.py`)", "",
        "Every trained model: its name, the exact configuration it was trained with, and its results.",
        "All runs: 15 epochs, cosine LR decay, mixed precision, best epoch kept by validation AUC, "
        "decision thresholds set on validation (5 % false alarms).",
        "Files for run `NAME`: weights `outputs/exp007/NAME/best.pt`, config `outputs/exp007/NAME/config.json`, "
        "results `outputs/exp007/NAME/metrics.json`, per-sample predictions `outputs/exp007/NAME/predictions.csv`, "
        "TensorBoard `outputs/tensorboard/NAME`, training log `outputs/exp007/logs/NAME.log`.", "",
        "**Naming:** `sd_` = siamese_diff, `ef_` = early_fusion, `dino_` = dino_frozen, `norvia_` = NORVIA-only data; "
        "`_s1`/`_s2` = seed 1/2; `_more` = + extra data; `_bin` = yes/no loss only; `depth1/3` = encoder depth; "
        "`_448`/`_896` = input width; `exp012_raw` = EXP-012 (un-straightened input).", "",
        "**Final model: `e14_consistent`** (EXP-014, consistent data). Previous best: `sd_depth1_more`.", "",
        "| run | architecture | encoder | input | training data | loss | optimiser | batch | seed | other | best epoch | val AUC (set) | test NORVIA AUC | unseen-font AUC |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        star = "**" if r["run"] == "e14_consistent" else ""
        lines.append(f"| {star}{r['run']}{star} | {r['arch']} | {r['encoder']} | {r['input']} | {r['data']} | {r['loss']} | "
                     f"{r['opt']} | {r['batch']} | {r['seed']} | {r['other']} | {r['best_epoch']} | "
                     f"{r['val']} ({r['val_set']}) | {r['test_d2']} | {r['unseen']} |")
    lines += ["", "Val AUC on the NORVIA-only validation set is not directly comparable with the mixed validation set. "
              "Compare runs on the test NORVIA column, and within the same validation set."]
    out = ROOT / "experiments" / "EXP-007_model_registry.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} runs -> {out}")


if __name__ == "__main__":
    main()
